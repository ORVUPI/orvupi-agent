export function locale() {
  const root = document.documentElement;
  const value = root.getAttribute("data-locale") || root.lang || "es";
  if (value.toLowerCase().startsWith("pt")) return "pt-BR";
  if (value.toLowerCase().startsWith("ja")) return "ja";
  if (value.toLowerCase().startsWith("ko")) return "ko";
  if (value.toLowerCase().startsWith("en")) return "en";
  return "es";
}

export function t(key, vars) {
  const bag = DICT[locale()] || DICT.es;
  let text = bag[key] ?? DICT.es[key] ?? key;
  if (text && typeof text === "object") return text;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = String(text).replaceAll(`{${name}}`, String(value ?? ""));
  }
  return text;
}

export function labelOf(group, value) {
  const bag = t(group);
  if (bag && typeof bag === "object" && value != null && bag[value]) return bag[value];
  return value || t("unavailable");
}

